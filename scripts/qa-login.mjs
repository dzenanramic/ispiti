import { chromium } from 'playwright';
const BASE = 'https://ispiti-eta.vercel.app';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await page.goto(`${BASE}/login`, { waitUntil: 'networkidle' });
await page.fill('#email', 'admin@ispiti.local');
await page.fill('#password', 'LX3aomU787JEgjXai3RV');
await page.click('button[type=submit]');
await page.waitForTimeout(3000);
console.log('URL', page.url());
console.log('BODY', (await page.locator('body').innerText()).slice(0, 300).replace(/\n/g, ' | '));
await page.screenshot({ path: '.qa/01-admin-dashboard.png', fullPage: true });
await browser.close();
